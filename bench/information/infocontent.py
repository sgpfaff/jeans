"""Which observable carries the information about sigma/m?

Ground truth is generated BY the model, so there is no misspecification at
all: any failure to recover is information content or sampler behaviour, not
physics mismatch. That is the thing the EAGLE run could not separate.

Three likelihoods on the same mock halo:

    rho    the spherically averaged density profile   (X-Stream-like)
    q      the isodensity axis-ratio profile          (Curve-Away-like)
    both

and the comparison is the posterior width on sigma/m. The literature
expectation is that shape is the discriminator for SIDM, so if that ordering
does not come out, either the model disagrees with two published forecasts or
the implementation is wrong -- and both are worth knowing.
"""
import os, sys, time
import numpy as np
from scipy.optimize import brentq

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "src"))
from jeanie.solver2d import solve_axisymmetric
from jeanie import jaxouter as JO

GN, CONV, T_AGE = 4.302e-6, 4.685e9, 10.0

# A galaxy-scale host, not a cluster: the EAGLE halos were 1e13-1e14, where a
# dominant BCG can erase the core entirely.
# sigma/m = 0.5 rather than 1: the ceiling for this halo is ~1.2, and a
# truth near the boundary would give a truncated posterior and confuse the
# very thing being measured.
TRUTH = dict(M200=1.0e12, c=10.0, sigma_m=0.5)
Q0 = 0.7                      # flattened outer halo, so there IS shape to see
MD, AD, BD = 6.0e10, 3.0, 0.28
R_RHO = np.geomspace(0.4, 25.0, 20)     # kpc, where a density profile is measured
R_Q = np.geomspace(0.6, 14.0, 12)       # kpc, inside r1, where shape is measured
SIG_RHO, SIG_Q = 0.05, 0.02             # 5% in density (dex-ish), 0.02 absolute in q


def disc(r, th):
    return -GN * MD / np.sqrt(r ** 2 * np.sin(th) ** 2
                              + (AD + np.sqrt(BD ** 2 + r ** 2 * np.cos(th) ** 2)) ** 2)


def solve_at(M200, c, r1):
    rho1, M1, J_L = JO.boundary_data(M200, c, r1, q0=Q0, L_list=(0, 2))
    res = solve_axisymmetric(r1, float(rho1), float(M1),
                             J_L=[float(v) for v in J_L], L_list=(0, 2),
                             Phi_b=disc)
    return res, float(rho1)


def sigma_m_at(M200, c, r1):
    res, rho1 = solve_at(M200, c, r1)
    if not res.success:
        return None, None
    return CONV / (rho1 * (4.0 * res.sigma0 / np.sqrt(np.pi)) * T_AGE), res


_LAST_R1 = {}          # per-process; workers each handle many calls


def _bracket_r1(M200, c, target, n=12):
    """The safe route: walk out, then bisect. ~24 solves. Used as a fallback."""
    rvir = float(JO.einasto_params(M200, c, 0.18)[2])
    lo = 0.004 * rvir
    slo, _ = sigma_m_at(M200, c, lo)
    if slo is None or slo > target:
        return None, None
    hi, shi = lo, slo
    for f in np.geomspace(0.006, 0.45, 12):
        r = f * rvir
        s, _ = sigma_m_at(M200, c, r)
        if s is None:
            break
        if s > target:
            hi, shi = r, s
            break
        lo, slo = r, s
    if shi <= target:
        return None, None
    for _ in range(n):
        mid = np.sqrt(lo * hi)
        s, _ = sigma_m_at(M200, c, mid)
        if s is None:
            return None, None
        lo, hi = (mid, hi) if s < target else (lo, mid)
    r1 = np.sqrt(lo * hi)
    _, res = sigma_m_at(M200, c, r1)
    return r1, res


def r1_for(M200, c, target, tol=2e-3, max_it=9):
    """Solve sigma/m(r1) = target for r1.

    sigma/m is monotone increasing in r1 AND smooth, so a secant in
    (log r1, log sigma/m) converges in four or five solves from a decent
    start, against about twenty-four for walk-then-bisect. Consecutive
    likelihood calls differ by a hair, so the previous answer is a very good
    start -- cached per worker process.

    Every step is clamped to the feasible range, and a step that lands where
    no solution exists is pulled back toward the last good point rather than
    abandoned, because the existence boundary is a real cliff here: past some
    r1 the matching problem has no solution at all. Anything that fails falls
    back to the bracketed version, which cannot miss.
    """
    rvir = float(JO.einasto_params(M200, c, 0.18)[2])
    lo_b, hi_b = np.log(0.003 * rvir), np.log(0.48 * rvir)
    lt = np.log(target)

    x0 = np.log(np.clip(_LAST_R1.get("r1", 0.05 * rvir),
                        np.exp(lo_b), np.exp(hi_b)))
    s0, res0 = sigma_m_at(M200, c, np.exp(x0))
    if s0 is None:
        return _bracket_r1(M200, c, target)
    if abs(np.log(s0) - lt) < tol:
        _LAST_R1["r1"] = np.exp(x0)
        return np.exp(x0), res0

    x1 = np.clip(x0 + (0.25 if np.log(s0) < lt else -0.25), lo_b, hi_b)
    s1, res1 = sigma_m_at(M200, c, np.exp(x1))
    if s1 is None:                       # stepped off the cliff
        x1 = 0.5 * (x0 + x1)
        s1, res1 = sigma_m_at(M200, c, np.exp(x1))
        if s1 is None:
            return _bracket_r1(M200, c, target)

    for _ in range(max_it):
        if abs(np.log(s1) - lt) < tol:
            _LAST_R1["r1"] = np.exp(x1)
            return np.exp(x1), res1
        d = np.log(s1) - np.log(s0)
        if abs(d) < 1e-12:
            break
        x2 = x1 - (np.log(s1) - lt) * (x1 - x0) / d
        if not np.isfinite(x2):
            break
        x2 = float(np.clip(x2, lo_b, hi_b))
        s2, res2 = sigma_m_at(M200, c, np.exp(x2))
        if s2 is None:
            x2 = 0.5 * (x1 + x2)
            s2, res2 = sigma_m_at(M200, c, np.exp(x2))
            if s2 is None:
                return _bracket_r1(M200, c, target)
        x0, s0 = x1, s1
        x1, s1, res1 = x2, s2, res2

    return _bracket_r1(M200, c, target)


def observables(res, r1, M200=None, c=None):
    """(rho_bar(R_RHO), q(R_Q)). Radii beyond r1 fall back to the outer halo.

    M200/c describe THIS model's outer halo. They default to the truth only so
    that generating the mock stays a one-liner; a likelihood must pass its own,
    or every radius outside r1 returns the same number for every model in the
    chain and those points carry no information at all.
    """
    if M200 is None:
        M200 = TRUTH["M200"]
    if c is None:
        c = TRUTH["c"]
    th, w = np.polynomial.legendre.leggauss(16)
    th, w = np.arccos(np.clip(0.5 * (th + 1.0), -1, 1)), 0.5 * w
    rho = np.empty_like(R_RHO)
    for i, r in enumerate(R_RHO):
        if r <= r1:
            rho[i] = float(np.sum(w * np.array([res.rho(r, t) for t in th])))
        else:
            rho[i] = float(JO.rho_sph_avg(r, M200, c, q0=Q0))
    q = np.empty_like(R_Q)
    for i, r in enumerate(R_Q):
        if r >= r1:
            q[i] = np.nan; continue
        def f(qq):
            a = res.rho(r * qq ** (-1 / 3.0), np.pi / 2)
            b = res.rho(r * qq ** (2 / 3.0), 0.0)
            return float(np.log(a / b))
        try:
            q[i] = brentq(f, 0.2, 5.0)
        except Exception:
            q[i] = np.nan
    return rho, q
